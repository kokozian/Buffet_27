num1 = int(input("Please enter a number : "))
num2 = int(input("Please enter a number: "))
symbol = input("Please enter one of the above +,-,*,/ : ")

if symbol == "+":
    print(num1+num2)
elif symbol == "-":
    print(num1-num2)
elif symbol == "*":
    print(num1*num2)    
elif symbol == "/":
    print(num1/num2)            